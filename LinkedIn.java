class LinkedIn {

    public static void createProfile(String name, String password) {
        System.out.println("Name: " + name);
        System.out.println("Password: " + password);
    }

    public static void createProfile(String name, String email, String profession, String password) {
        System.out.println("Name: " + name);
        System.out.println("Email: " + email);
        System.out.println("Profession: " + profession);
        System.out.println("Password: " + password);
    }
}