class ZomatoOrder {
    private int id;
    private String food;
    private double cost;

    public void setId(int id) {
	this.id = id; 
	}
    public void setFood(String food) {
	this.food = food; 
	}
    public void setCost(double cost) {
	this.cost = cost;
	}

    public int getId() { 
	return id; 
	}
    public String getFood() {
	return food;
	}
    public double getCost() { 
	return cost; 
	}
}

