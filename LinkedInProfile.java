class LinkedInProfile {
    private int id;
    private String name;
    private String skill;

    public void setId(int id) { 
	this.id = id;
	}
    public void setName(String name) {
	this.name = name; 
	}
    public void setSkill(String skill) { 
	this.skill = skill; 
	}

    public int getId() { 
	return id; 
	}
    public String getName() { 
	return name; 
	}
    public String getSkill() { 
	return skill; 
	}
}